"""Тематичне оцінювання за §12–§15: комбінаторика, ймовірність, статистика.

Обсяг – увесь §3 підручника Мерзляка (математика, 11 клас): комбінаторні
правила суми та добутку (§12), перестановки, розміщення й комбінації (§13),
класичне означення ймовірності (§14) і вибіркові характеристики (§15 – розмах,
середнє значення, медіана, мода). Упор на комбінаторику й ймовірність: по
п'ять задач на кожну, на вибіркові характеристики дві.

НОВОЇ МАТЕМАТИКИ ТУТ НЕМА, і це навмисно. §12–§15 уже покриті трьома банками
(combinatorics.py, probability.py, statistics.py – разом 30 шаблонів), а
підсумкова робота й має повторювати пройдене. Нове тут інше – СЛОТ.

СЛОТ – це одне питання тесту, за яким стоїть не один шаблон, а кілька
рівноцінних з тієї самої теми. Котрий дістанеться студентові, вирішує його
власний rng, тобто той самий HMAC-сид, з якого беруться числа умови. Отже
вибір задачі відтворюється при перезаході в тест і змінюється разом з числами,
коли питання перевидається.

ЧОМУ СЛОТИ, А НЕ ПРОСТО БІЛЬШИЙ БАНК. Рушій вибирає питання так: тасує банк
сидом студента й бере перші question_count (app/service.py, _pick_question_keys).
Якби ми поклали в банк усі 24 ключі й лишили 12 питань, мішанина тем гуляла б
від студента до студента: одному чотири задачі зі статистики, іншому жодної.
Оцінка за підсумкову роботу має бути порівнянною, тож тему питання тримає
незмінною слот, а різною робить саму задачу.

ПРОТИ СПИСУВАННЯ. Числа в кожного свої й так, у кожному тесті. Слоти додають
те, чого числа не дають, – свій НАБІР ЗАДАЧ: 2·2·2·2·4 (комбінаторика) ×
2·2·2·2·4 (ймовірність) × 2·2 (статистика) = 16 384 набори, і це ще без
порядку питань, який теж у кожного свій. Практичний сенс простий: групи
складають тест одна за одною, і знання, «що було в тесті» у першої групи,
другій майже нічого не дає – у неї інші задачі, а не лише інші числа.

Набори слотів НЕ ПЕРЕТИНАЮТЬСЯ: один шаблон не може дістатися студентові
двічі в одній роботі (це перевіряє tests/test_probability_thematic.py).
"""

import random

from engine import TEMPLATES, Question, template

# Слот -> рівноцінні шаблони, з яких він вибирає.
SLOTS: dict[str, tuple[str, ...]] = {}

# Надбавка часу на задачу в підсумковій роботі. Викладач переглянув тест і
# сказав, що на комбінаторику й ймовірність часу замало, а на вибіркові
# характеристики – нормально. Надбавку кладемо СЮДИ, а не в самі шаблони:
# тести combinatorics і probability студенти вже здавали, і час у них
# змінюватися не повинен.
EXTRA = 45
SLOW: dict[str, int] = {}


def _slot(key: str, *candidates: str, bonus: int = 0) -> None:
    """Реєструє слот як звичайний шаблон, що пускає один із рівноцінних."""

    def build(rng: random.Random) -> Question:
        chosen = rng.choice(candidates)
        q = TEMPLATES[chosen](rng)
        q.seconds += bonus
        # Ключем питання рушій поставить ключ слота (engine.build), тож
        # справжній шаблон лишаємо в параметрах: видно в журналі й в розборі,
        # яку саме задачу отримав студент.
        q.params = dict(q.params, shape=chosen)
        return q

    template(key)(build)
    SLOTS[key] = candidates
    SLOW[key] = bonus


# --------------------------------------------------------------------------
# §12–§13. Комбінаторика – п'ять слотів
# --------------------------------------------------------------------------

# Правила суми та добутку в чистому вигляді: маршрути або меню.
_slot("mt_rules", "cmb_sum_product", "cmb_menu", bonus=EXTRA)

# Цифрові задачі: набір із нулем (нуль не може бути першим) або парність.
_slot("mt_digits", "cmb_digits_zero", "cmb_digits_parity", bonus=EXTRA)

# Ті самі правила, але рівень ••: кратність 2, 4, 5, 25 або паролі змінної
# довжини (правило суми над степенями).
_slot("mt_rules_hard", "cmb_divisible", "cmb_sequences", bonus=EXTRA)

# Самі формули сполук: $P_n = n!$ або пара «розміщення проти комбінацій».
_slot("mt_formulas", "cmb_permutations", "cmb_arrangements_vs_combinations",
      bonus=EXTRA)

# Застосування $C_n^k$. Чотири кандидати, бо шаблонів на це найбільше.
_slot("mt_choose", "cmb_team_with_fixed", "cmb_polygon", "cmb_exactly_k",
      "cmb_two_lines", bonus=EXTRA)

# --------------------------------------------------------------------------
# §14. Ймовірність – п'ять слотів
# --------------------------------------------------------------------------

# Саме означення $P = \frac{m}{n}$ на вибиранні одного предмета; тут же
# достовірна й неможлива події, тобто межі 0 і 1.
_slot("mt_classic", "pb_urn", "pb_cards", bonus=EXTRA)

# Множина чисел $1..N$: просте / складене / одноцифрове або кратність.
_slot("mt_numbers", "pb_number_kind", "pb_multiples", bonus=EXTRA)

# Задачі, де рівноможливі результати спершу треба порахувати самому:
# числа з даних цифр або забуті цифри коду.
_slot("mt_count_then_chance", "pb_digits", "pb_code", bonus=EXTRA)

# Пара з групи: хлопець і дівчина або парність добутку та суми.
_slot("mt_pair", "pb_pair_mixed", "pb_pair_parity", bonus=EXTRA)

# Ймовірність через сполуки й межі означення: усі одного виду, рівно a
# одного виду, найменша кількість для $P = 1$, обернена задача.
_slot("mt_combinations_chance", "pb_all_of_kind", "pb_exactly", "pb_guaranteed",
      "pb_inverse", bonus=EXTRA)

# --------------------------------------------------------------------------
# §15. Вибіркові характеристики – два слоти
# --------------------------------------------------------------------------
# Беремо саме ХАРАКТЕРИСТИКИ вибірки, як їх означує §15. Два шаблони банку
# статистики сюди не входять: st_ordered має поле «так / ні» (а його можна
# вгадати), а st_population питає про генеральну сукупність, тобто не про
# вибіркову характеристику.

# Усі чотири показники – розмах, середнє, медіана, мода – за переліком даних
# або за стовпчиковою діаграмою (РИСУНОК).
_slot("mt_sample_stats", "st_sample", "st_diagram")

# Середнє значення, яке треба спершу зібрати: за таблицею частот або за
# вибіркою з нулів та одиниць.
_slot("mt_sample_mean", "st_frequency", "st_scores")
